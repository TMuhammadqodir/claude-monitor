export const LANGS = { uz: 'O‘zbekcha', en: 'English', ru: 'Русский' };

function stored(key, value) {
  try {
    if (value === undefined) return localStorage.getItem(key);
    localStorage.setItem(key, value);
  } catch {
    return null;
  }
}

/** The viewer's choice, else the browser's language when it is one of these, else English. */
function pick() {
  const chosen = stored('lang');
  if (LANGS[chosen]) return chosen;
  for (const tag of navigator.languages ?? [navigator.language ?? '']) {
    const code = String(tag).slice(0, 2).toLowerCase();
    if (LANGS[code]) return code;
  }
  return 'en';
}

export const lang = pick();

/** Remembers the language and draws the page again in it. */
export function setLang(code) {
  if (!LANGS[code] || code === lang) return;
  stored('lang', code);
  location.reload();
}

